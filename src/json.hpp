#pragma once
// ============================================================================
// Сборка JSON-ответов.
//
// Две вещи:
//   1. jesc()  — экранирует строку, чтобы она безопасно вставилась в JSON.
//   2. JObj    — «умный» конструктор объекта: сам ставит запятые между
//                полями, сам оборачивает строки в кавычки.
//
// Пример:
//     JObj o;
//     o.str("name", "Alice");
//     o.int_("age", 30);
//     o.num("score", 4.5);
//     return o.str();  // {"name":"Alice","age":30,"score":4.5}
// ============================================================================

#include <string>
#include <sstream>

// ---------------------------------------------------------------------------
// Экранирование строки для JSON.
//
// JSON требует экранировать: " \ \n \r \t
// (остальные управляющие символы на практике не встречаются в наших данных,
// поэтому их игнорируем — для учебного проекта этого достаточно).
// ---------------------------------------------------------------------------
inline std::string jesc(const std::string& s) {
    std::string out;
    out.reserve(s.size() + 8); // грубая оценка, чтобы избежать реаллокаций
    for (char c : s) {
        switch (c) {
            case '"':  out += "\\\""; break;
            case '\\': out += "\\\\"; break;
            case '\n': out += "\\n";  break;
            case '\r': out += "\\r";  break;
            case '\t': out += "\\t";  break;
            default:   out += c;      break;
        }
    }
    return out;
}

// ---------------------------------------------------------------------------
// Сборщик JSON-объекта.
//
// Использование:
//     JObj o;
//     o.str("error", "not found");   // строка →  "error":"not found"
//     o.num("price", 19.99);         // число →   "price":19.99
//     o.int_("count", 5);            // целое →   "count":5
//     o.raw("data", "[1,2,3]");      // вставить как есть (уже готовый JSON)
//
// Пустое значение в raw() превращается в null — удобно для необязательных
// полей (например, mode может отсутствовать).
// ---------------------------------------------------------------------------
struct JObj {
    std::string body;   // накапливаемое содержимое без внешних фигурных скобок

    // Ставит запятую между полями, если это не первое поле.
    void sep() { if (!body.empty()) body += ','; }

    // Строковое поле (значение экранируется).
    void str(const std::string& k, const std::string& v) {
        sep();
        body += "\"" + k + "\":\"" + jesc(v) + "\"";
    }

    // Дробное число. std::stringstream сам подберёт точность.
    void num(const std::string& k, double v) {
        sep();
        std::stringstream ss;
        ss << v;
        body += "\"" + k + "\":" + ss.str();
    }

    // Целое число (в т.ч. long long — для id, счётчиков).
    void int_(const std::string& k, long long v) {
        sep();
        body += "\"" + k + "\":" + std::to_string(v);
    }

    // Вставить готовый JSON как есть. Пустая строка → null.
    void raw(const std::string& k, const std::string& v) {
        sep();
        body += "\"" + k + "\":" + (v.empty() ? "null" : v);
    }

    // Явный null (когда нужно «поле есть, но пустое»).
    void null_(const std::string& k) {
        sep();
        body += "\"" + k + "\":null";
    }

    // Итоговая строка с фигурными скобками.
    std::string str() const { return "{" + body + "}"; }
};

// ---------------------------------------------------------------------------
// Хелпер для сборки массива из уже готовых элементов.
//
// Пример:
//     JArray a;
//     a.add(o1.str());
//     a.add(o2.str());
//     return a.str();  // [{...},{...}]
// ---------------------------------------------------------------------------
struct JArr {
    std::string body;

    void add(const std::string& element) {
        if (!body.empty()) body += ',';
        body += element;
    }

    std::string str() const { return "[" + body + "]"; }
};